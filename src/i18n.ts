const dicts: Record<Locale, typeof zh> = { 'zh-CN': zh, 'en-US': en }

export function t(locale: Locale, key: keyof typeof zh, ...args: Array<string | number>): string {
  const dict = dicts[locale] || zh
  const template = dict[key] ?? zh[key] ?? String(key)
  return template.replace(/\{(\d+)\}/g, (_all, index: string) => String(args[Number(index)] ?? ''))
}